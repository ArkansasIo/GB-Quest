#!/usr/bin/env node
// Patch notes: patch-notes.json is the one source of truth.
//   node tools/patch-notes.cjs            write src/patch_notes.js (the copy the game reads)
//   node tools/patch-notes.cjs --check    exit 1 if src/patch_notes.js is out of date
//   node tools/patch-notes.cjs --markdown <version>   print that release's notes as Markdown (GitHub release body)
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'patch-notes.json');
const OUT = path.join(ROOT, 'src', 'patch_notes.js');

function load() {
  const data = JSON.parse(fs.readFileSync(SRC, 'utf8'));
  if (!data || !Array.isArray(data.releases) || !data.releases.length) throw new Error('patch-notes.json needs a releases list');
  for (const r of data.releases) {
    if (!/^\d+\.\d+\.\d+$/.test(r.version)) throw new Error(`bad version ${r.version}`);
    if (!Array.isArray(r.sections)) throw new Error(`${r.version}: sections missing`);
  }
  return data;
}
function render(data) {
  return "'use strict';\n// GENERATED by tools/patch-notes.cjs from patch-notes.json. Edit that file, not this one.\n" +
    `window.GBQ_PATCH_NOTES = ${JSON.stringify(data, null, 1)};\n`;
}
function markdown(data, version) {
  const r = data.releases.find(x => x.version === version);
  if (!r) throw new Error(`no release ${version} in patch-notes.json`);
  const lines = [`## v${r.version}${r.title ? ` — ${r.title}` : ''}`, '', `Released ${r.date || ''}`.trim(), ''];
  for (const s of r.sections) { lines.push(`### ${s.name}`, ''); for (const n of s.notes) lines.push(`- ${n}`); lines.push(''); }
  lines.push('**Downloads:** `gbquest-itch-html5.zip` (upload to itch.io as an HTML game), `gbquest.html` (play in any browser), and the source code zip below.');
  return lines.join('\n');
}

if (require.main === module) {
  const args = process.argv.slice(2), data = load();
  if (args[0] === '--markdown') { process.stdout.write(markdown(data, args[1] || data.releases[0].version) + '\n'); process.exit(0); }
  const text = render(data);
  if (args[0] === '--check') {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur.replace(/\r/g, '') !== text) { console.error('src/patch_notes.js is out of date: run node tools/patch-notes.cjs'); process.exit(1); }
    console.log('patch notes up to date'); process.exit(0);
  }
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${data.releases.length} releases, latest v${data.releases[0].version})`);
}
module.exports = { load, render, markdown };
